-- ============================================================================
-- Views (lifecycle filters)
-- ============================================================================

-- Queue of messages to process, due, in FIFO order.
create view msg.v_pending_outbox as
select *
from   msg.outbox
where  status = 'pending'
  and  next_attempt_at <= now()
order  by outbox_id;

-- Definitive failures awaiting inspection or manual resend.
create view msg.v_dead_letter as
select *
from   msg.outbox
where  status = 'dead_letter';

-- ============================================================================
-- Indexes
-- ============================================================================

-- Worker claim: due pending rows, in FIFO order.
create index ix_outbox_due on msg.outbox (next_attempt_at, outbox_id) where status = 'pending';

-- Purge job: scan of past deadlines on terminal rows.
create index ix_outbox_purge_at on msg.outbox (purge_at) where status <> 'pending';

-- Idempotency: uniqueness of (compartment, key) when a key is provided. Nulls not
-- distinct, so that the shared space (compartment null) is one space too.
create unique index ux_outbox_idempotency on msg.outbox (compartment, idempotency_key) nulls not distinct
  where idempotency_key is not null;

-- Dead-letter lookup by compartment.
create index ix_outbox_dead_letter on msg.outbox (compartment) where status = 'dead_letter';

