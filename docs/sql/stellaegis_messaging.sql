-- ============================================================================
-- Stellaegis Messaging — Database schema (msg)
-- ============================================================================
-- Database: stellaegis_messaging
-- Schema:   msg
-- No cross-database joins.
-- All constraints explicitly named.
--
-- Isolation regime: pooled, correlated by tenant_slug — same reasons as
-- trash/doc (a cross-cutting transport buffer, no guaranteed cohabitation with
-- the business databases). See _workspace/_planning/messaging-refonte.md § 5
-- (Send engine) and _workspace/todo.md [MESSAGING].
--
-- Outbox = reliable transport buffer (retries/backoff/dead-letter), not an
-- emailing system (deliverability is delegated to the relay). Channel-agnostic:
-- the channel discriminant + an opaque serialized payload let SMS reuse the same
-- table/worker later, WITHOUT unifying message and transport.
--
-- No internal relation (no child table): a bigint surrogate is nonetheless kept
-- here — unlike trash.items — for the worker's FIFO ordering and index locality
-- on a high-churn table (insert/delete). The public uuid (outbox_unique_id) is the
-- STABLE message-id: idempotency, dead-letter, and anchor of the future tracking
-- module (see § 9 of the design).
--
-- Prerequisite: pgcrypto extension (symmetric encryption of msg.outbox.payload
-- via pgp_sym_encrypt — body + recipients = personal data). See the column
-- comment, and stellaegis_secrets.sql for the vault mechanism.
-- ============================================================================

create schema if not exists msg;

create extension if not exists pgcrypto;

-- Transport channel. Adding a future channel = ALTER TYPE msg.channel ADD VALUE.
create type msg.channel as enum ('email', 'sms');

-- Lifecycle of an outbox entry.
--   pending     : awaiting send / retry (retry window ~24 h).
--   sent        : sent successfully (persists only if "Sent items" retention is
--                 enabled; fire-and-forget by default = deletion).
--   dead_letter : retries exhausted -> DEFINITIVE failure, kept for inspection /
--                 manual resend, purged after the dead-letter TTL (default 30 d).
create type msg.outbox_status as enum ('pending', 'sent', 'dead_letter');

-- ============================================================================
-- Outbox
-- ============================================================================
-- Sending is a distributed problem (non-transactional network send): the entry
-- is written first, then a worker claims it (SELECT ... FOR UPDATE SKIP LOCKED on
-- the due rows), attempts the send, and updates the state. Optional idempotency
-- by (tenant_slug, idempotency_key) neutralizes a replay.
-- ============================================================================

create table msg.outbox (
  outbox_id         bigint            generated by default as identity,
  outbox_unique_id  uuid              not null default gen_random_uuid(),
  tenant_slug       text              not null,
  channel           msg.channel       not null,
  status            msg.outbox_status not null default 'pending',
  payload           bytea             not null,
  key_slot          smallint          not null default 1,
  idempotency_key   text,
  transport_name    text,
  attempts          integer           not null default 0,
  next_attempt_at   timestamptz       not null default now(),
  last_error        text,
  created_at        timestamptz       not null default now(),
  sent_at           timestamptz,
  failed_at         timestamptz,
  purge_at          timestamptz       not null default 'infinity'::timestamptz,

  constraint pk_outbox primary key (outbox_id),
  constraint uq_outbox_unique_id unique (outbox_unique_id),
  constraint ck_outbox_tenant_slug check (
    tenant_slug ~ '^[a-z][a-z0-9-]{2,62}$' and tenant_slug !~ '--'
  ),
  constraint ck_outbox_attempts check (attempts >= 0),
  constraint ck_outbox_key_slot check (key_slot in (1, 2)),
  constraint ck_outbox_idempotency_key check (
    idempotency_key is null or char_length(idempotency_key) between 1 and 200
  ),
  constraint ck_outbox_transport_name check (
    transport_name is null or char_length(transport_name) between 1 and 64
  ),
  constraint ck_outbox_last_error check (
    last_error is null or char_length(last_error) <= 4096
  ),
  constraint ck_outbox_status_dates check (
       (status = 'pending'     and sent_at is null     and failed_at is null)
    or (status = 'sent'        and sent_at is not null  and failed_at is null)
    or (status = 'dead_letter' and failed_at is not null)
  )
);

