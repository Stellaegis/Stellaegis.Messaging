-- ============================================================================
-- Stellaegis Messaging — Database schema (msg), for the PostgreSQL outbox
-- ============================================================================
-- Schema:   msg, in whichever database the outbox's connection string names.
-- Requires: PostgreSQL 15 or later (unique index with nulls not distinct).
-- All constraints explicitly named.
--
-- Outbox = reliable transport buffer (retries, backoff, dead letter), not an
-- emailing system: deliverability belongs to the relay. Channel-agnostic: a
-- channel discriminant and an opaque serialized payload let another channel
-- reuse the same table and worker, without unifying message and transport.
--
-- Each row belongs to a space: a compartment, or the shared space (compartment
-- null). The space resolves the transport configuration at send time.
--
-- Prerequisite: pgcrypto extension (symmetric encryption of msg.outbox.payload
-- via pgp_sym_encrypt — body and recipients are personal data).
-- ============================================================================

create schema if not exists msg;

create extension if not exists pgcrypto;

-- Transport channel. Adding a channel = alter type msg.channel add value.
create type msg.channel as enum ('email', 'sms');

-- Lifecycle of an outbox entry.
--   pending     : awaiting send or retry.
--   sent        : sent successfully; persists only when sent-item retention is
--                 enabled (by default a sent entry is deleted).
--   dead_letter : retries exhausted -> definitive failure, kept for inspection
--                 or manual resend, purged after the dead-letter TTL.
create type msg.outbox_status as enum ('pending', 'sent', 'dead_letter');

-- ============================================================================
-- Outbox
-- ============================================================================
-- Sending is a distributed problem (a network send is not transactional): the
-- entry is written first, then a worker claims it (select ... for update skip
-- locked on the due rows), attempts the send, and updates the state. Optional
-- idempotency by (compartment, idempotency_key) neutralizes a replay.
--
-- outbox_id joins nothing. It exists for the worker's FIFO order and for index
-- locality on a high-churn table (insert, then delete): created_at holds the
-- start of the transaction, so rows inserted together share it, and a random
-- uuid key would fragment the index. outbox_unique_id is the public message id.
-- ============================================================================

create table msg.outbox (
  outbox_id         bigint            generated by default as identity,
  outbox_unique_id  uuid              not null default gen_random_uuid(),
  compartment       text,
  channel           msg.channel       not null,
  status            msg.outbox_status not null default 'pending',
  payload           bytea             not null,
  key_slot          smallint          not null default 1,
  idempotency_key   text,
  transport_name    text,
  attempts          integer           not null default 0,
  next_attempt_at   timestamptz       not null default now(),
  last_error        text,
  created_at        timestamptz       not null default now(),
  sent_at           timestamptz,
  failed_at         timestamptz,
  purge_at          timestamptz,

  constraint pk_outbox primary key (outbox_id),
  constraint uq_outbox_unique_id unique (outbox_unique_id),
  constraint ck_outbox_compartment check (
    compartment is null or compartment ~ '^(?!.*--)[a-z][a-z0-9-]{1,61}[a-z0-9]$'
  ),
  constraint ck_outbox_attempts check (attempts >= 0),
  constraint ck_outbox_key_slot check (key_slot in (1, 2)),
  constraint ck_outbox_idempotency_key check (
    idempotency_key is null or char_length(idempotency_key) between 1 and 200
  ),
  constraint ck_outbox_transport_name check (
    transport_name is null or char_length(transport_name) between 1 and 64
  ),
  constraint ck_outbox_last_error check (
    last_error is null or char_length(last_error) <= 4096
  ),
  constraint ck_outbox_status_dates check (
       (status = 'pending'     and sent_at is null     and failed_at is null     and purge_at is null)
    or (status = 'sent'        and sent_at is not null and failed_at is null     and purge_at is not null)
    or (status = 'dead_letter' and failed_at is not null                         and purge_at is not null)
  )
);

